from pathlib import Path
from PIL import Image
import struct,re,uuid
root=Path(__file__).resolve().parents[1]
meta=(root/'UI/Textures/BN/Glyphs.edds.meta').read_text(encoding='utf-8-sig')
def dds(image, relative, guid):
 image=image.convert('RGBA');w,h=image.size
 header=struct.pack('<4s7I11I8I5I',b'DDS ',124,0x100F,h,w,w*4,0,1,*([0]*11),32,4,int.from_bytes(b'DX10','little'),0,0,0,0,0,0x1000,0,0,0,0)
 out=root/relative;out.parent.mkdir(parents=True,exist_ok=True)
 out.write_bytes(header+struct.pack('<5I',29,3,0,1,3)+image.tobytes())
 out.with_name(out.name+'.meta').write_text(re.sub(r'Name "[^"]+"',f'Name "{{{guid}}}{relative}"',meta,count=1),encoding='utf-8')
atlas=Image.open(root/'UI/Textures/BN/Glyphs.edds').convert('RGBA')
data=(root/'Scripts/Game/BN/BN_GlyphData.c').read_text(encoding='utf-8-sig')
indices=[int(x) for x in re.findall(r'indices.Set\(.*?, (\d+)\);',data)]
lookup=['// Generated by Tools/build_news_assets.py', 'class BN_GlyphResources {', ' static void Init(array<ResourceName> textures) {']
for index in indices:
 x=index%32*64;y=index//32*96
 relative=f'UI/Textures/BN/GlyphCells/G_{index}.edds'
 guid=uuid.uuid5(uuid.NAMESPACE_URL,'blca-news:'+relative).hex[:16].upper()
 dds(atlas.crop((x,y,x+64,y+96)),relative,guid)
 lookup.append(f'  textures.Insert("{{{guid}}}{relative}");')
lookup += [' }','}']
(root/'Scripts/Game/BN/BN_GlyphResources.c').write_text('\n'.join(lookup)+'\n',encoding='utf-8')
dds(Image.open(root/'Tools/NewsSources/BLCA_Logo.png'),'UI/Textures/BN/ServerLogo.edds','16F849822AA54A70')
print(f'{len(indices)} standalone glyph cells and server logo exported')
