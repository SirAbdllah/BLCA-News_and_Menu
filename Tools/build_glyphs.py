"""Rebuild the OFL font atlas and its Enforce lookup table. Requires Pillow."""
from pathlib import Path
import unicodedata as U
import struct
from PIL import Image, ImageFont, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(str(ROOT/'Tools/NotoSansArabic.ttf'), 44)
forms = {}
for n in range(0xFB50, 0xFF00):
    d = U.decomposition(chr(n)).split()
    if len(d) == 2 and d[0] in ('<isolated>', '<final>', '<initial>', '<medial>'):
        base = int(d[1], 16)
        if 0x600 <= base <= 0x6FF:
            forms.setdefault(base, {})[d[0][1:-1]] = n
chars = set(range(32,127)) | set(range(0x600,0x700))
for fs in forms.values(): chars.update(fs.values())
# Lam-alef presentation ligatures, selected before contextual shaping.
chars.update(range(0xFEF5,0xFEFD))
chars = sorted(chars)
W,H,CW,CH=2048,4096,64,96
atlas=Image.new('RGBA',(W,H)); draw=ImageDraw.Draw(atlas)
lines=['// Generated by Tools/build_glyphs.py; glyph baselines share y=65.',
       'class BN_GlyphData {',
       ' static void Init(map<string,int> indices, array<float> widths, map<string,string> forms) {']
for i,n in enumerate(chars):
    c=chr(n); x=(i%32)*CW; y=(i//32)*CH
    draw.text((x+3,y+65),c,font=font,fill='white',anchor='ls')
    escaped=c.replace('\\','\\\\').replace('"','\\"')
    width=max(1,min(58,float(font.getlength(c))))
    lines += [f'  indices.Set("{escaped}", {i}); widths.Insert({width:.3f});']
for base,fs in forms.items():
    # Four UTF-8 glyphs separated by | so byte string indexing is never used on a character.
    variants='|'.join(chr(fs.get(k,fs.get('isolated',base))) for k in ('isolated','final','initial','medial'))
    # Prefix flags: connects to preceding / following logical character.
    flags=('1' if 'final' in fs else '0')+('1' if 'initial' in fs else '0')
    lines += [f'  forms.Set("{chr(base)}", "{flags}|{variants}");']
lines += [' }','}']
header=struct.pack('<4s7I11I8I5I', b'DDS ',124,0x100F,H,W,W*4,0,1,*([0]*11),32,4,int.from_bytes(b'DX10','little'),0,0,0,0,0,0x1000,0,0,0,0)
(ROOT/'UI/Textures/BN/Glyphs.edds').write_bytes(header+struct.pack('<5I',29,3,0,1,3)+atlas.tobytes())
(ROOT/'Scripts/Game/BN/BN_GlyphData.c').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'{len(chars)} glyphs generated')

